#!/usr/bin/env python3
"""
build_showcase.py: refresh the Devnixplus showcase page (showcase/) from demos/.

  venv/Scripts/python tools/build_showcase.py            list + screenshot every demo
  venv/Scripts/python tools/build_showcase.py --no-shots  only rewrite showcase/demos.js
  venv/Scripts/python tools/build_showcase.py --only seasons-salon   re-shoot one demo

Writes showcase/demos.js (title, category, city, rating per demo) and
showcase/thumbs/<slug>.jpg (a screenshot of the top of each demo).
Screenshots need Playwright + Pillow in the venv (see requirements.txt).
"""
import argparse
import functools
import http.server
import io
import json
import re
import sys
import threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from new_demo import CATEGORIES, DEMOS, guess_city, read_field  # noqa: E402

SHOWCASE = ROOT / "showcase"
THUMBS = SHOWCASE / "thumbs"
VIEWPORT = {"width": 1280, "height": 800}
THUMB_WIDTH = 640


def read_number(text, key):
    m = re.search(r"^\s{2}%s:\s*([0-9.]+)" % re.escape(key), text, re.M)
    return float(m.group(1)) if m else None


def collect():
    demos = []
    for folder in sorted(p for p in DEMOS.iterdir() if (p / "data.js").exists()):
        data = (folder / "data.js").read_text(encoding="utf-8")
        category = read_field(data, "category") or "general"
        reviews = read_number(data, "reviewCount")
        demos.append({
            "slug": folder.name,
            "name": read_field(data, "name") or folder.name,
            "category": category,
            "label": CATEGORIES.get(category, CATEGORIES["general"])[1],
            "city": read_field(data, "city") or guess_city(read_field(data, "address")),
            "tagline": read_field(data, "tagline"),
            "rating": read_number(data, "rating"),
            "reviews": int(reviews) if reviews else None,
            "sample": folder.name.startswith("sample-"),
            "thumb": "thumbs/%s.jpg" % folder.name if (THUMBS / ("%s.jpg" % folder.name)).exists() else "",
        })
    return demos


def write_js(demos):
    body = json.dumps(demos, ensure_ascii=False, indent=2)
    (SHOWCASE / "demos.js").write_text(
        "/* Generated by tools/build_showcase.py: do not edit by hand. */\nwindow.DEMOS = %s;\n" % body,
        encoding="utf-8")


def serve_demos():
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *args):
            pass

    handler = functools.partial(Quiet, directory=str(DEMOS))
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    return server


def shoot(slugs):
    try:
        from PIL import Image
        from playwright.sync_api import sync_playwright
    except ImportError:
        sys.exit("Playwright/Pillow missing: venv/Scripts/python -m pip install -r requirements.txt")
    THUMBS.mkdir(parents=True, exist_ok=True)
    server = serve_demos()
    base = "http://127.0.0.1:%d" % server.server_address[1]
    hide = ".demo-ribbon, #demo-ribbon, .theme-switcher, #floating { display: none !important; }"
    with sync_playwright() as p:
        browser = p.chromium.launch()
        ctx = browser.new_context(viewport=VIEWPORT, device_scale_factor=1, reduced_motion="reduce")
        for slug in slugs:
            page = ctx.new_page()
            try:
                page.goto("%s/%s/" % (base, slug), wait_until="networkidle", timeout=30000)
                page.wait_for_selector("#boot-loader", state="detached", timeout=10000)
                page.add_style_tag(content=hide)
                page.wait_for_timeout(600)
                img = Image.open(io.BytesIO(page.screenshot(type="png")))
                img = img.convert("RGB").resize((THUMB_WIDTH, THUMB_WIDTH * VIEWPORT["height"] // VIEWPORT["width"]), Image.LANCZOS)
                img.save(THUMBS / ("%s.jpg" % slug), "JPEG", quality=82, optimize=True, progressive=True)
                print("  shot %s" % slug)
            except Exception as e:  # keep going: one broken demo shouldn't stop the rest
                print("  ! %s: %s" % (slug, e))
            finally:
                page.close()
        browser.close()
    server.shutdown()


def main():
    ap = argparse.ArgumentParser(description="Refresh showcase/ from demos/.")
    ap.add_argument("--no-shots", action="store_true", help="skip screenshots, only rewrite demos.js")
    ap.add_argument("--only", metavar="SLUG", help="screenshot just this demo")
    a = ap.parse_args()

    slugs = [d["slug"] for d in collect()]
    if a.only and a.only not in slugs:
        sys.exit("demo '%s' not found in %s" % (a.only, DEMOS))
    if not a.no_shots:
        shoot([a.only] if a.only else slugs)
    demos = collect()
    write_js(demos)
    print("Wrote showcase/demos.js (%d demos)" % len(demos))


if __name__ == "__main__":
    main()
