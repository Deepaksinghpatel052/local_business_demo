def guess_city(address):
    """Same rule as guessCity() in main.js."""
    parts = [p.strip() for p in str(address or "").split(",") if p.strip()]
    if not parts:
        return ""
    last = parts[-1]
    if (re.search(r"\d{6}", last) or re.match(r"^[A-Z]{2}\b", last)) and len(parts) > 1:
        return parts[-2]
    return re.sub(r"\s*\d{6}\s*$", "", last)


def _parse_time(s):
    m = re.match(r"^(\d{1,2})(?::(\d{2}))?\s*(am|pm)?$", str(s).strip().lower().replace(".", ":"))
    if not m:
        return None
    h, mi = int(m.group(1)), int(m.group(2) or 0)
    if m.group(3) == "pm" and h < 12:
        h += 12
    if m.group(3) == "am" and h == 12:
        h = 0
    return None if h > 24 or mi > 59 else h * 60 + mi


def parse_day(v):
    """Port of parseDay() in main.js."""
    s = str(v or "").strip().lower()
    if not s or re.search(r"closed|holiday|\boff\b", s):
        return {"closed": True}
    if re.search(r"24\s*(h|hours|hrs)|open\s*24|00:00\s*-\s*24:00", s):
        return {"allDay": True}
    ranges = []
    for part in re.split(r"[,;&]|\band\b", s):
        p = re.split(r"\s*(?:-|–|—|\bto\b)\s*", part.strip())
        if len(p) != 2:
            continue
        a, b = _parse_time(p[0]), _parse_time(p[1])
        if a is not None and b is not None:
            ranges.append([a, b + 1440 if b <= a else b])
    return {"ranges": ranges} if ranges else {"closed": True}


def _hhmm(m):
    if m >= 1440:
        m = 1439 if m == 1440 else m - 1440
    return "%02d:%02d" % (m // 60, m % 60)


def seo_facts(data, page_url, asset_base):
    cat = category(data.get("category"))
    name = data.get("name") or "Local Business"
    city = data.get("city") or guess_city(data.get("address"))
    seo = data.get("seo") or {}
    title = seo.get("title") or "%s | %s%s" % (name, cat["title"], (" in " + city) if city else "")
    tagline = data.get("tagline") or "%s%s" % (cat["title"], (" in " + city) if city else "")
    desc = seo.get("description") or "%s. %s%s" % (
        tagline, (data["address"] + ". ") if data.get("address") else "", ("Call %s." % data["phone"]) if data.get("phone") else "")
    desc = desc.replace("..", ".")[:160]
    hero = data.get("heroImage") or ""
    if not hero:
        hero = asset_base + "placeholders/%s/hero.jpg" % cat["photos"]
    image = urljoin(page_url, hero)
    ld = {
        "@context": "https://schema.org", "@type": cat["schema"], "name": name,
        "description": data.get("about") or data.get("tagline") or None,
        "image": image, "logo": urljoin(page_url, data["logo"]) if data.get("logo") else None,
        "telephone": data.get("phone") or None, "email": data.get("email") or None, "url": page_url,
        "foundingDate": data.get("established") or None, "founder": data.get("owner") or None,
    }
    if data.get("address"):
        pin = re.search(r"\b\d{6}\b", data["address"])
        ld["address"] = {"@type": "PostalAddress", "streetAddress": data["address"], "addressLocality": city or None,
                         "postalCode": pin.group(0) if pin else None, "addressCountry": "IN"}
    if data.get("rating") and data.get("reviewCount"):
        ld["aggregateRating"] = {"@type": "AggregateRating", "ratingValue": data["rating"],
                                 "reviewCount": data["reviewCount"], "bestRating": 5}
    same = [v for v in (data.get("social") or {}).values() if v]
    if data.get("googleUrl"):
        same.append(data["googleUrl"])
    if same:
        ld["sameAs"] = same
    hours = data.get("hours") or {}
    if any(hours.get(d) for d in DAY_KEYS):
        spec = []
        for i, d in enumerate(DAY_KEYS):
            day = parse_day(hours.get(d))
            if day.get("closed"):
                continue
            for r in ([[0, 1439]] if day.get("allDay") else day["ranges"]):
                spec.append({"@type": "OpeningHoursSpecification", "dayOfWeek": SCHEMA_DAYS[i],
                             "opens": _hhmm(r[0]), "closes": _hhmm(r[1])})
        ld["openingHoursSpecification"] = spec
    ld = _drop_none(ld)
    return {"title": title, "description": desc, "image": image, "ld": ld, "site_name": name}


def _drop_none(v):
    if isinstance(v, dict):
        return {k: _drop_none(x) for k, x in v.items() if x is not None}
    return v


