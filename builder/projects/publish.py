def shared_dir():
    return settings.SITES_ROOT / "_shared" / settings.SHARED_VERSION


def sync_shared(force=False):
    """Copy template/css, js and placeholders into SITES_ROOT/_shared/<version>/."""
    dest = shared_dir()
    if dest.exists() and not force:
        return dest
    tmp = dest.with_name(".tmp-%s-%s" % (dest.name, secrets.token_hex(4)))
    tmp.mkdir(parents=True)
    for item in ("css", "js", "placeholders"):
        shutil.copytree(settings.TEMPLATE_DIR / item, tmp / item)
    _swap_in(tmp, dest)
    return dest


def site_dir(slug):
    if not re.match(r"^[a-z0-9][a-z0-9-]{0,59}$", slug):
        raise ValueError("bad slug %r" % slug)
    return settings.SITES_ROOT / slug


def _swap_in(tmp, target):
    """Replace `target` by the fully written `tmp` folder with renames, so a half-written
    site is never served (each rename is atomic; the old copy is deleted afterwards)."""
    old = None
    if target.exists():
        old = target.with_name(".old-%s-%s" % (target.name, secrets.token_hex(4)))
        os.rename(target, old)
    os.rename(tmp, target)
    if old is not None:
        shutil.rmtree(old, ignore_errors=True)


def _link_or_copy(src, dst):
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def _copy_images(project, dest):
    images = dest / "images"
    images.mkdir()
    for im in project.images.all():
        try:
            _link_or_copy(im.file.path, images / im.filename)
        except FileNotFoundError:
            log.warning("missing image file %s", im.file.name)


def mode_for(project):
    from .models import Project
    if project.status in (Project.SUSPENDED, Project.EXPIRED, Project.REJECTED):
        return "unavailable"
    if project.status == Project.LIVE:
        return "live"
    return "preview"


def publish_project(project, mode="auto"):
    """Write SITES_ROOT/<slug>/ for `project` and record what was published."""
    if mode == "auto":
        mode = mode_for(project)
    target = site_dir(project.slug)
    settings.SITES_ROOT.mkdir(parents=True, exist_ok=True)

    if mode == "unpublish":
        if target.exists():
            old = target.with_name(".old-%s-%s" % (target.name, secrets.token_hex(4)))
            os.rename(target, old)
            shutil.rmtree(old, ignore_errors=True)
        project.published_mode = ""
        project.save(update_fields=["published_mode"])
        return None

    sync_shared()
    tmp = settings.SITES_ROOT / (".tmp-%s-%s" % (project.slug, secrets.token_hex(4)))
    tmp.mkdir()
    try:
        if mode == "unavailable":
            (tmp / "index.html").write_text(UNAVAILABLE_HTML, encoding="utf-8")
        else:
            data = site_data(project)
            extra = {}
            if mode == "live":
                extra["reportUrl"] = app_url("/report/%s/" % project.slug)
            page = render_index(data, mode=mode, page_url=project.public_url if mode == "live" else project.site_url,
                                asset_base=shared_path(), config_extra=extra)
            (tmp / "index.html").write_text(page, encoding="utf-8")
            (tmp / "data.js").write_text(data_js_text(data), encoding="utf-8")
            _copy_images(project, tmp)
        _swap_in(tmp, target)
    except Exception:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    project.published_mode = mode
    project.published_at = timezone.now()
    project.save(update_fields=["published_mode", "published_at"])
    return target


