def render_index(data, *, mode, page_url, asset_base, config_extra=None, inline_data=False):
    """mode: preview | live | editor | download."""
    page = (settings.TEMPLATE_DIR / "index.html").read_text(encoding="utf-8")
    e = lambda s: html.escape(str(s), quote=True)
    facts = seo_facts(data, page_url, asset_base)

    noindex = mode in ("preview", "editor")
    page = re.sub(r'[ \t]*<!-- DEMO:NOINDEX[^>]*-->\r?\n', "", page)
    page = re.sub(r'[ \t]*<meta name="robots" content="noindex, nofollow">\r?\n',
                  '  <meta name="robots" content="noindex, nofollow">\n' if noindex else "", page)

    meta = (
        "<!-- META: rendered by the Devnixplus platform -->\n"
        "  <title>%s</title>\n"
        '  <meta name="description" content="%s">\n'
        '  <meta property="og:type" content="website">\n'
        '  <meta property="og:site_name" content="%s">\n'
        '  <meta property="og:title" content="%s">\n'
        '  <meta property="og:description" content="%s">\n'
        '  <meta property="og:image" content="%s">\n'
        '  <meta property="og:url" content="%s">\n'
        '  <meta name="twitter:card" content="summary_large_image">\n'
        '  <link rel="canonical" href="%s">\n'
        '  <script type="application/ld+json" id="ld-business">%s</script>'
    ) % (e(facts["title"]), e(facts["description"]), e(facts["site_name"]), e(facts["title"]),
         e(facts["description"]), e(facts["image"]), e(page_url), e(page_url), js_json(facts["ld"]))
    start, end = page.index(META_START), page.index(META_END) + len(META_END)
    page = page[:start] + meta + page[end:]

    if asset_base:
        page = page.replace('href="css/style.css"', 'href="%scss/style.css"' % e(asset_base))
        page = page.replace('src="js/themes.js"', 'src="%sjs/themes.js"' % e(asset_base))
        page = page.replace('src="js/main.js"', 'src="%sjs/main.js"' % e(asset_base))

    config = {"demoMode": mode in ("preview", "editor"), "mode": mode, "assetBase": asset_base,
              "themeSwitcher": False}
    config.update(config_extra or {})
    boot = '<script>window.LBD_CONFIG = %s;</script>\n  ' % js_json(config)
    if inline_data:
        boot += "<script>window.BUSINESS = %s;</script>" % js_json(data)
        page = page.replace('<script src="data.js" defer></script>', boot)
    else:
        page = page.replace('<script src="data.js" defer></script>', boot + '<script src="data.js" defer></script>')
    return page


