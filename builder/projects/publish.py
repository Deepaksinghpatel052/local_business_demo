def js_json(value, indent=None):
    """JSON that is also safe inside <script>: no "</script>", "<!--", U+2028/2029 can survive."""
    out = json.dumps(value, ensure_ascii=False, indent=indent)
    # "<" only ever appears inside JSON strings, so \u003c is an exact, valid replacement.
    # It covers "</script>" and "<!--"; the line separators are not valid raw in older JS engines.
    return (out.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
            .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


def site_data(project):
    """The data written to data.js: the stored data plus the fields the platform controls."""
    data = dict(project.data or {})
    data["slug"] = project.slug
    data["category"] = data.get("category") or project.category
    data["developer"] = dict(DEVELOPER)   # keeps the "Website by Devnixplus" credit
    return data


def data_js_text(data):
    return "/* Generated by Devnixplus. Edit this website at %s */\nwindow.BUSINESS = %s;\n" % (
        app_url("/dashboard/"), js_json(data, indent=1))


