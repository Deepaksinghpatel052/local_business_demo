def build_download_zip(project):
    """A fresh, self-contained ZIP from the latest data (relative paths, no _shared)."""
    from core.models import PlatformSettings
    ps = PlatformSettings.load()
    data = site_data(project)
    cat = category(data.get("category"))
    page_url = project.public_url
    page = render_index(data, mode="download", page_url=page_url, asset_base="",
                        config_extra={"demoMode": False})
    buf = io.BytesIO()
    tpl = settings.TEMPLATE_DIR
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("index.html", page)
        z.writestr("data.js", data_js_text(data))
        for sub in ("css", "js"):
            for f in sorted((tpl / sub).rglob("*")):
                if f.is_file():
                    z.write(f, f.relative_to(tpl).as_posix())
        ph = tpl / "placeholders" / cat["photos"]
        for f in sorted(ph.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(tpl).as_posix())
        if (tpl / "placeholders" / "CREDITS.md").exists():
            z.write(tpl / "placeholders" / "CREDITS.md", "placeholders/CREDITS.md")
        for im in project.images.all():
            try:
                z.write(im.file.path, "images/" + im.filename)
            except FileNotFoundError:
                pass
        fmt = {"name": project.business_name, "slug": project.slug, "app": settings.APP_URL,
               "wa": ps.support_whatsapp, "email": ps.support_email, "date": timezone.localdate().isoformat()}
        z.writestr("README.txt", README_TXT.format(**fmt))
        z.writestr("LICENSE.txt", LICENSE_TXT.format(**fmt))
    return buf.getvalue()
