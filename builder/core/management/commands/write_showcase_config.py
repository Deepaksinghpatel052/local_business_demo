"""
Write showcase/config.js so the showcase's "Use this design" buttons point at APP_URL from .env:

    python manage.py write_showcase_config
"""
import json

from django.conf import settings
from django.core.management.base import BaseCommand


class Command(BaseCommand):
    help = "Write showcase/config.js with the builder address (APP_URL) from .env"

    def handle(self, *args, **opts):
        path = settings.REPO_DIR / "showcase" / "config.js"
        path.write_text("// Generated by: manage.py write_showcase_config (from APP_URL in .env). Do not edit.\n"
                        "window.DEVNIX_APP_URL = %s;\n" % json.dumps(settings.APP_URL), encoding="utf-8")
        self.stdout.write(self.style.SUCCESS("Wrote %s (APP_URL %s)" % (path, settings.APP_URL)))
